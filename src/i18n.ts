export type MessageKey = keyof typeof messages.en

export function t(locale: Locale, key: MessageKey, vars?: Record<string, string | number>) {
  let text: string = messages[locale][key] ?? messages.en[key]
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value))
    }
  }
  return text
}

const BUILDING_KEYS: Record<string, MessageKey> = {
  'Block A — Engineering': 'bA',
  'Block B — IT & CS': 'bB',
  'Block C — Administration': 'bC',
  Library: 'bLib',
  Cafeteria: 'bCafe',
  'Sports Complex': 'bSports',
  'Dormitory Zone': 'bDorm'
}

const CATEGORY_KEYS: Record<string, MessageKey> = {
  classroom: 'catClassroom',
  lab: 'catLab',
  restroom: 'catRestroom',
  electrical: 'catElectrical',
  plumbing: 'catPlumbing',
  other: 'catOther'
}

const CONDITION_KEYS: Record<string, MessageKey> = {
  good: 'condGood',
  fair: 'condFair',
  poor: 'condPoor',
  critical: 'condCritical'
}

export function buildingLabel(locale: Locale, name: string) {
  const key = BUILDING_KEYS[name]
  return key ? t(locale, key) : name
}

export function categoryLabel(locale: Locale, category: string) {
  const key = CATEGORY_KEYS[category]
  return key ? t(locale, key) : category
}

export function conditionLabel(locale: Locale, condition: string) {
  const key = CONDITION_KEYS[condition]
  return key ? t(locale, key) : condition
}

export function statusLabel(locale: Locale, status: string) {
  if (status === 'queued') return t(locale, 'queued')
  if (status === 'synced') return t(locale, 'synced')
  if (status === 'draft') return t(locale, 'draft')
  return status
}

export function isLocale(value: string | null | undefined): value is Locale {
  return value === 'en' || value === 'vi'
}
